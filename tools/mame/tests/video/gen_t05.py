#!/usr/bin/env python3
"""Generate t05.cmd: tests 5 + 6 (software text cursor at the DOS prompt, scrolling, the 2048-word
wrap, fn 0Ah BX=1). Each step dumps the text RAM (tNNN.txt, screenraw incl. start) and the
resident data (rNNN.bin). CRTC writes are logged (watchw e8000 2) to check that the driver never
writes R14/R15. analyze_text.py checks the dumps."""
RES = 0x2CE0
out = ["""# Tests 5/6 (generated by gen_t05.py): text cursor, scroll, wrap, fn 0Ah BX=1
waittext >
waitidle 1
sh @FEED@ --hello M --port $(cat @RUN@/pty_a) > @RUN@/feed.log 2>&1 & echo $! > @RUN@/feed.pid
wait 0.5
type B:CTMV9K /SA\\n
waittext Installed
sh kill $(cat @RUN@/feed.pid)
waitidle 1
peek cc 4
type CLS\\n
waitidle 1
type B:V9KMT s4q\\n
waittext fn 4 -> B=00 X=790
waitidle 1
watchw e8000 2"""]
n = [0]


def dump(label):
    i = n[0]; n[0] += 1
    out.extend(['wait 0.3', 'print step %03d %s' % (i, label), 'screenraw @OUT@/t%03d.txt' % i,
                'mem %x 100 @OUT@/r%03d.bin' % (RES, i)])


def move(label, *moves):
    i = n[0]
    s = '\\n'.join('move %d %d' % m for m in moves)
    out.append("sh (printf '%s\\n' | @FEED@ --script /dev/stdin --port $(cat @RUN@/pty_a) "
               ">> @RUN@/feed.log 2>&1; touch @RUN@/flag_%d) &" % (s, i))
    out.append('waitfile @RUN@/flag_%d' % i)
    dump(label)


def typ(label, text):
    out.extend(['type %s' % text, 'waitidle 1'])
    dump(label)


dump('after V9KMT s4q (799,399)')
move('move', (-100, -50))
move('move', (-30, -100))
move('move', (55, 33))
move('move', (-1000, -1000))
move('move', (7, 17))
typ('DIR scrolled, no move yet', 'DIR\\n')
move('move after scroll', (20, 20))
move('move', (100, 40))
for k in range(6):
    typ('DIR', 'DIR\\n')
move('after 6 DIRs', (5, 5))
move('bottom right', (1000, 1000))
move('left on bottom row', (-200, 0))
move('row 23', (0, -16))
move('far left bottom', (-1000, 0))
for k in range(4):
    typ('DIR', 'DIR\\n')
move('after 4 DIRs', (3, 3))
move('bottom right', (1000, 1000))
move('bottom', (-40, 0))
# test 6: fn 0Ah BX=1 (CX=0 DX=7) while V9KMT waits for keys
typ('CLS', 'CLS\\n')
out.append('type B:V9KMT s\\n')
out.append('waittext fn 01 AX')
out.append('waitidle 1')
dump('V9KMT s')
move('move before fn 0Ah', (-20, -20))
out.append('print CRTC before fn 0Ah')
out.append('items :11a')
out.append('print fn 0Ah')
out.append('type a')
out.append('waittext fn 0A AX')
out.append('waitidle 1')
dump('V9KMT after a')
out.append('items :11a')
move('move after fn 0Ah', (-50, -50))
move('move after fn 0Ah', (30, 10))
out.append('items :11a')
out += ['type q', 'waitidle 1']
dump('V9KMT after q')
# BIOS scroll artifact: cursor at column 0 of the bottom row while the console scrolls
move('bottom left', (-1000, 1000))
typ('DIR with cursor at bottom-left', 'DIR\\n')
move('move away', (100, -100))
out += ['unwatch', 'snap', 'exit']
open(__file__.replace('gen_t05.py', 't05.cmd'), 'w').write('\n'.join(out) + '\n')
print(n[0], 'steps')
