#!/usr/bin/env python3
"""Generate t07.cmd: tests 7 + 17 (graphics cursor edges, all 16 shifts) under PICASSO.
Each step: feed mouse packets (and optionally poke the resident hotspot first), then dump the
40000-byte bitmap (gNNN.bin) and the resident data (rNNN.bin). analyze_gfx.py checks them.
Hotspot pokes reach gx/gy that PICASSO's own shapes cannot (gx = X - hot.X with X clamped
to 0..799); PICASSO calls fn 9 only when the cursor changes region, after the big moves."""
RES = 0x2CE0        # resident segment 02CEh (INT 33h vector 02CE:0955), checked by the analysis
BMP = 0x3000        # dump window start: bitmap_seg = 2*(word F000:0000 & 7FFh) (R12 bit 4 = 0) moves
BLEN = 0x9C40 + 0x1000  # with the resident size (GETSCRN allocates it); the analysis slices it
HOT = RES + 0x78

hdr = """# Tests 7/17 (generated by gen_t07.py): PICASSO graphics cursor at all edges and shifts
waittext >
waitidle 1
sh @FEED@ --hello M --port $(cat @RUN@/pty_a) > @RUN@/feed.log 2>&1 & echo $! > @RUN@/feed.pid
wait 0.5
type B:CTMV9K /SA\\n
waittext Installed
sh kill $(cat @RUN@/feed.pid)
waitidle 1
peek cc 4
type B:\\n
waitidle 1
type GETSCRN\\n
waitidle 2
type PICASSO\\n
wait 35
peek f0000 2
items :11a
snap
"""
out = [hdr.rstrip('\n')]
n = [0]
labels = []


def h16(v):
    v &= 0xFFFF
    return '%02x %02x' % (v & 0xFF, v >> 8)


def step(label, moves=(), hot=None, snap=False):
    i = n[0]
    n[0] += 1
    if hot is not None:
        out.append('poke %x %s %s' % (HOT, h16(hot[0]), h16(hot[1])))
    if moves:
        s = '\\n'.join('move %d %d' % m for m in moves)
        out.append("sh (printf '%s\\n' | @FEED@ --script /dev/stdin --port $(cat @RUN@/pty_a) "
                   ">> @RUN@/feed.log 2>&1; touch @RUN@/flag_%d) &" % (s, i))
        out.append('waitfile @RUN@/flag_%d' % i)
    out.append('wait 0.3')
    out.append('print step %03d %s' % (i, label))
    out.append('mem %x %x @OUT@/g%03d.bin' % (BMP, BLEN, i))
    out.append('mem %x 100 @OUT@/r%03d.bin' % (RES, i))
    if snap:
        out.append('snap')
    labels.append(label)


step('ref', snap=True)
# right edge: X = 799, hot 0,0, then X 798..783 (gx = X)
step('right natural', [(1000, 0)])
step('right gx=799', [(1, 0)], hot=(0, 0), snap=True)
for k in range(16):
    step('right step', [(-1, 0)])
# left edge: X = 0, hot 15,0, then X 1..31 (gx = X - 15)
step('left natural', [(-1000, 0)])
step('left gx=-15', [(-1, 0)], hot=(15, 0), snap=True)
for k in range(31):
    step('left step', [(1, 0)])
# top: X = 400, Y = 0, hot 0,15, then Y 1..31 (1 mickey per pixel with the 8/8 ratio)
step('top natural', [(400, 0), (0, -1000)])
step('top gy=-15', [(0, -1)], hot=(0, 15), snap=True)
for k in range(31):
    step('top step', [(0, 1)])
# bottom: Y = 399, hot 0,0, then Y 398..383
step('bottom natural', [(0, 1000)])
step('bottom gy=399', [(0, 1)], hot=(0, 0), snap=True)
for k in range(16):
    step('bottom step', [(0, -1)])
# corners (natural shape first, then poked hot spot)
step('TL natural', [(-1000, -1000)])
step('TL -15,-15', [(-1, -1)], hot=(15, 15), snap=True)
step('TL hidden gx=-16', [(-1, -1)], hot=(16, 0))
step('TL hidden gy=-16', [(-1, -1)], hot=(0, 16))
step('TR natural', [(1000, 0)])
step('TR 799,-15', [(1, -1)], hot=(0, 15), snap=True)
step('TR hidden gx=800', [(1, -1)], hot=(-1, 0))
step('BR natural', [(0, 1000)])
step('BR 799,399', [(1, 1)], hot=(0, 0), snap=True)
step('BR hidden gy=400', [(1, 1)], hot=(0, -1))
step('BL natural', [(-1000, 0)])
step('BL -15,399', [(-1, 1)], hot=(15, 0), snap=True)
step('BL 0,384', [(-1, 1)], hot=(0, 15))
step('centre', [(400, -200)], snap=True)
out.append('exit')
open(__file__.replace('gen_t07.py', 't07.cmd'), 'w').write('\n'.join(out) + '\n')
print(n[0], 'steps')
